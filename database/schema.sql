-- FlightInsight / Stage 3
-- PostgreSQL 17; initial schema based on BTS Jan-Mar 2025 profiles.
-- Loaded automatically by the PostgreSQL Docker image on first database initialization.

CREATE TABLE airlines (
    airline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline_code VARCHAR(10) NOT NULL UNIQUE,
    airline_name TEXT,
    bts_airline_id INTEGER,
    CONSTRAINT airlines_code_nonblank CHECK (length(btrim(airline_code)) > 0)
);

CREATE TABLE airports (
    airport_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_code VARCHAR(10) NOT NULL UNIQUE,
    airport_name TEXT,
    bts_airport_id INTEGER,
    city TEXT,
    state VARCHAR(2),
    CONSTRAINT airports_code_nonblank CHECK (length(btrim(airport_code)) > 0)
);

CREATE TABLE import_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL,
    source_sha256 CHAR(64) NOT NULL UNIQUE,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    rows_processed INTEGER NOT NULL DEFAULT 0,
    rows_loaded INTEGER NOT NULL DEFAULT 0,
    rows_rejected INTEGER NOT NULL DEFAULT 0,
    rows_skipped INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(12) NOT NULL DEFAULT 'running',
    error_message TEXT,
    CONSTRAINT import_batches_filename_nonblank CHECK (length(btrim(filename)) > 0),
    CONSTRAINT import_batches_sha256_valid CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT import_batches_counts_nonnegative CHECK (
        rows_processed >= 0 AND rows_loaded >= 0 AND
        rows_rejected >= 0 AND rows_skipped >= 0
    ),
    CONSTRAINT import_batches_status_valid CHECK (status IN ('running', 'completed', 'failed'))
);

CREATE TABLE flights (
    flight_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_date DATE NOT NULL,
    airline_id BIGINT NOT NULL REFERENCES airlines(airline_id),
    flight_number VARCHAR(15) NOT NULL,
    origin_airport_id BIGINT NOT NULL REFERENCES airports(airport_id),
    destination_airport_id BIGINT NOT NULL REFERENCES airports(airport_id),

    -- BTS HHMM is local clock time and can include 2400.
    -- Store HHMM as small integers to retain source meaning and distinguish 0000/2400.
    -- These fields are not UTC timestamps.
    scheduled_departure_hhmm SMALLINT NOT NULL,
    actual_departure_hhmm SMALLINT,
    scheduled_arrival_hhmm SMALLINT NOT NULL,
    actual_arrival_hhmm SMALLINT,

    -- Signed delays: negative = early; NULL = not applicable / not known.
    departure_delay NUMERIC(9,2),
    arrival_delay NUMERIC(9,2),
    cancelled BOOLEAN NOT NULL,
    diverted BOOLEAN NOT NULL,
    cancellation_code CHAR(1),

    -- Delay-cause values are nonnegative minutes, NULL when not reported.
    carrier_delay NUMERIC(9,2),
    weather_delay NUMERIC(9,2),
    nas_delay NUMERIC(9,2),
    security_delay NUMERIC(9,2),
    late_aircraft_delay NUMERIC(9,2),

    import_batch_id BIGINT NOT NULL REFERENCES import_batches(batch_id),

    CONSTRAINT flights_number_nonblank CHECK (length(btrim(flight_number)) > 0),
    CONSTRAINT flights_scheduled_dep_hhmm_valid CHECK (
        scheduled_departure_hhmm = 2400 OR
        (scheduled_departure_hhmm BETWEEN 0 AND 2359 AND
         scheduled_departure_hhmm % 100 BETWEEN 0 AND 59)
    ),
    CONSTRAINT flights_actual_dep_hhmm_valid CHECK (
        actual_departure_hhmm IS NULL OR actual_departure_hhmm = 2400 OR
        (actual_departure_hhmm BETWEEN 0 AND 2359 AND
         actual_departure_hhmm % 100 BETWEEN 0 AND 59)
    ),
    CONSTRAINT flights_scheduled_arr_hhmm_valid CHECK (
        scheduled_arrival_hhmm = 2400 OR
        (scheduled_arrival_hhmm BETWEEN 0 AND 2359 AND
         scheduled_arrival_hhmm % 100 BETWEEN 0 AND 59)
    ),
    CONSTRAINT flights_actual_arr_hhmm_valid CHECK (
        actual_arrival_hhmm IS NULL OR actual_arrival_hhmm = 2400 OR
        (actual_arrival_hhmm BETWEEN 0 AND 2359 AND
         actual_arrival_hhmm % 100 BETWEEN 0 AND 59)
    ),
    CONSTRAINT flights_cancellation_code_valid CHECK (
        cancellation_code IS NULL OR cancellation_code IN ('A', 'B', 'C', 'D')
    ),
    CONSTRAINT flights_causes_nonnegative CHECK (
        (carrier_delay IS NULL OR carrier_delay >= 0) AND
        (weather_delay IS NULL OR weather_delay >= 0) AND
        (nas_delay IS NULL OR nas_delay >= 0) AND
        (security_delay IS NULL OR security_delay >= 0) AND
        (late_aircraft_delay IS NULL OR late_aircraft_delay >= 0)
    ),
    -- Candidate key observed to be unique in each of the three BTS files.
    -- Prevents duplicate loads of the same scheduled flight.
    CONSTRAINT flights_source_identity_unique UNIQUE (
        flight_date, airline_id, flight_number,
        origin_airport_id, destination_airport_id, scheduled_departure_hhmm
    )
);

-- The unique flights key already begins with flight_date, so it can serve
-- date-only lookups. Other indexes support the main dashboard filters.
CREATE INDEX idx_flights_airline_date ON flights (airline_id, flight_date);
CREATE INDEX idx_flights_origin_date ON flights (origin_airport_id, flight_date);
CREATE INDEX idx_flights_destination_date ON flights (destination_airport_id, flight_date);
CREATE INDEX idx_flights_import_batch ON flights (import_batch_id);
CREATE INDEX idx_flights_delayed_date ON flights (flight_date)
    WHERE NOT cancelled AND NOT diverted AND arrival_delay >= 15;
